const fs = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const dir = path.resolve(__dirname,'..');
  const repo = path.resolve(dir,'../..');
  const projectPath = path.join(dir,'프로젝트.json');
  const project = JSON.parse(await fs.readFile(projectPath,'utf8'));
  assert.notEqual(project.status,'published');
  const previous = JSON.parse(await fs.readFile(path.join(repo,'인스타툰/20261002-jnll7/프로젝트.json'),'utf8'));
  const board = JSON.parse(await fs.readFile(path.join(__dirname,'최종콘티.json'),'utf8'));
  const manifest = JSON.parse(await fs.readFile(path.join(__dirname,'이미지생성-기록.json'),'utf8'));
  assert.equal(manifest.pages.length,10);
  for(const item of manifest.pages) await fs.access(item.path);
  await fs.writeFile(path.join(__dirname,'그림연결전-프로젝트.json'),JSON.stringify(project,null,2));
  project.characters = previous.characters.map(c=>({...c,sheet:`인스타툰/${project.id}/캐릭터/01-보리-수진-미소-기준.png`}));
  project.sponsored = false;
  project.style = previous.style.replace('이번 제작은 2/3, 표지 포함 10장. 수진의 회사 앞에서 전달 후 그날 밤 단톡방으로 이어진다.','이번 제작은 마지막 3/3, 표지 포함 10장. 단톡방 반박 → 개인톡 정산 → 며칠 뒤 미소와 식사. 표지 3/3, 마지막 -끝-.');
  project.slides = board.cards.map((c,i)=>({layout:'single',fullBleed:true,panels:[{scene:c.scene+'\n표정: '+c.emotion,image:`인스타툰/${project.id}/컷/${path.basename(manifest.pages[i].path)}`,bubbles:[]}]}));
  project.status='illustrated'; project.updated_at=new Date().toISOString();
  await fs.writeFile(projectPath,JSON.stringify(project,null,2)+'\n');
  const planning = path.join(path.dirname(repo),'한술툰/기획');
  await fs.writeFile(path.join(planning,'첫사연-친구-3부-제작본.json'),JSON.stringify(board,null,2));
  await fs.writeFile(path.join(planning,'첫사연-친구-3부-제작본.md'),`# ${board.title} · 3/3\n\n`+board.cards.map((c,i)=>`## ${i+1}장\n\n${c.scene}\n\n${c.dialogue}\n\n표정: ${c.emotion}\n`).join('\n')+`\n## 캡션\n\n${board.caption}\n`);
  const res = await fetch(`http://localhost:3123/api/carousel/instatoon/${project.id}`);
  assert.ok(res.ok); const checked=await res.json();
  assert.deepEqual(checked.project.slides,project.slides);
  console.log(JSON.stringify({id:project.id,slides:project.slides.length,lint:checked.lint}));
})().catch(e=>{console.error(e);process.exitCode=1});
