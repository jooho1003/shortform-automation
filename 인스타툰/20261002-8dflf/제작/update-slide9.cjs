const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const dir=path.resolve(__dirname,'..');
  const repo=path.resolve(dir,'../..');
  const workspace=path.dirname(repo);
  const read=async p=>JSON.parse(await fs.readFile(p,'utf8'));
  const write=async(p,x)=>fs.writeFile(p,JSON.stringify(x,null,2)+'\n');
  const projectPath=path.join(dir,'프로젝트.json');
  const project=await read(projectPath);
  assert.notEqual(project.status,'published');
  const studioPath=path.join(repo,'인스타툰/시리즈/hansul.json');
  const studioBytes=await fs.readFile(studioPath,'utf8');
  const studio=JSON.parse(studioBytes);
  const episode=studio.episodes.find(e=>e.editorId===project.id);
  assert.ok(episode);
  const boardPath=path.join(__dirname,'최종콘티.json');
  const board=await read(boardPath);
  const revision=await read(path.join(__dirname,'9장-수정01-생성기록.json'));
  await write(path.join(__dirname,'9장수정전-프로젝트.json'),project);
  await fs.writeFile(path.join(__dirname,'9장수정전-작업실.json'),studioBytes);
  const card=board.cards[8];
  card.scene='며칠 뒤, 한술 식당에서 미소와 보리가 둘이 밥을 먹는다. 미소의 질문 말풍선을 오른쪽 위, 보리의 답변을 그 아래 왼쪽에 배치하여 발화 순서가 높낮이로 구별된다. 보리 옆 탁자에 놓인 휴대폰에 톡! 효과음·진동선·작은 알림 아이콘을 넣어 메시지 도착을 표현한다. 메시지 내용은 10장에서 확인한다.';
  card.dialogue='시간: 며칠 뒤\n미소: 나 또 연애 얘기해도 돼?\n보리: 그럼. 무슨 일 있었어?\n휴대폰 효과음: 톡!';
  project.slides[8].panels[0].image=`인스타툰/${project.id}/컷/09-수정01.png`;
  project.slides[8].panels[0].scene=card.scene+'\n표정: '+card.emotion;
  project.updated_at=new Date().toISOString();
  project.status='illustrated';
  episode.cards[8]=structuredClone(card);
  episode.version++;
  episode.updatedAt=project.updated_at;
  const draft=Object.fromEntries(['topic','cards','caption','brief','feedback','topicMode','storyboardMode'].map(k=>[k,structuredClone(episode[k])]));
  episode.history.push({version:episode.version,at:episode.updatedAt,label:'9장 그림 수정 · 톡 도착 표시와 발화 순서 배치',draft});
  studio.revision++;
  assert.equal(await fs.readFile(studioPath,'utf8'),studioBytes);
  await write(projectPath,project);
  await write(studioPath,studio);
  await write(boardPath,board);
  const manifestPath=path.join(__dirname,'이미지생성-기록.json');
  const manifest=await read(manifestPath);
  manifest.fixes.push({page:9,original:manifest.pages[8],reason:revision.request});
  manifest.pages[8]={page:9,source:revision.source,path:path.join(dir,revision.path),prompt:revision.prompt};
  await write(manifestPath,manifest);
  const planning=path.join(workspace,'한술툰/기획');
  await write(path.join(planning,'첫사연-친구-3부-제작본.json'),board);
  await fs.writeFile(path.join(planning,'첫사연-친구-3부-제작본.md'),`# ${board.title} · 3/3\n\n`+board.cards.map((c,i)=>`## ${i+1}장\n\n${c.scene}\n\n${c.dialogue}\n\n표정: ${c.emotion}\n`).join('\n')+`\n## 캡션\n\n${board.caption}\n`);
  await fs.appendFile(path.join(__dirname,'작업기록.md'),'\n## 9장 수정\n\n- 사용자 요청: 톡 도착 표시, 발화 순서에 따른 말풍선 높낮이.\n- 09-수정01.png: 미소 질문 위 → 보리 답변 아래. 휴대폰에 톡!·진동선·알림 아이콘 추가.\n- 그림·콘티·작업실 기록을 같은 수정본으로 연결.\n');
  await fs.appendFile(path.join(planning,'한술툰-설계.md'),'\n### 말풍선 배치 선호 — 2026-10-02\n\n- 말하는 순서에 따라 먼저 말하는 인물의 말풍선을 위, 답하는 말풍선을 아래에 분명히 배치한다.\n- 3/3 9장: 톡! 도착 표시를 넣고 10장의 메시지 확인으로 연결한다.\n');
  console.log(JSON.stringify({id:project.id,image:project.slides[8].panels[0].image,studioRevision:studio.revision}));
})().catch(e=>{console.error(e);process.exitCode=1});
